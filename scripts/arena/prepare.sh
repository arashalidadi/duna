#!/usr/bin/env bash
# Arena sandbox bring-up. Idempotent; safe to re-run after the sandbox recycles.
#
# What it does, in order:
#   1. writes a sandbox-only repo-root .env and apps/web/.env.local if missing
#   2. starts the local Prisma engine mirror (binaries.prisma.sh is not reachable)
#   3. starts/creates the embedded PostgreSQL 16 cluster and the API database
#   4. prisma generate + migrate deploy + seed (required reference data only)
#   5. builds the API and the web app
#
# It does NOT start long-lived services: in Arena, start them with the process
# tools so they are visible as live previews:
#
#   node scripts/arena/engine-mirror.mjs
#   PHASE11_APPROVED_DB_NAME=duna_seed_test bash scripts/start-api.sh
#   (cd apps/web && npx next start -H 0.0.0.0 -p 3000)
#
# Usage:
#   bash scripts/arena/prepare.sh [--skip-install] [--skip-build] [--with-demo]
set -Eeuo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

SKIP_INSTALL=0
SKIP_BUILD=0
WITH_DEMO=0
for arg in "$@"; do
  case "$arg" in
    --skip-install) SKIP_INSTALL=1 ;;
    --skip-build) SKIP_BUILD=1 ;;
    --with-demo) WITH_DEMO=1 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

SANDBOX_ID="${E2B_SANDBOX_ID:-}"
TOOLS_DIR="$REPO_ROOT/.arena-tools"
PG_PACKAGE="${ARENA_PG_PACKAGE:-@embedded-postgres/linux-x64@16.14.0-beta.17}"
DB_NAME="${ARENA_DB_NAME:-duna_seed_test}"
DB_ROLE="${ARENA_DB_ROLE:-shipping_runtime_p11}"
MIRROR_PORT="${PRISMA_MIRROR_PORT:-4555}"

mkdir -p "$TOOLS_DIR/logs" "$TOOLS_DIR/attachments"

step() { printf '\n=== %s ===\n' "$*"; }

# --------------------------------------------------------------------------
# 1. Environment files (never committed; .env and .env.local are gitignored)
# --------------------------------------------------------------------------
step "environment"
if [[ ! -f .env ]]; then
  PASSWORD_FILE="$TOOLS_DIR/runtime-db-password"
  if [[ -f "$PASSWORD_FILE" ]]; then
    DB_PASSWORD="$(cat "$PASSWORD_FILE")"
  else
    DB_PASSWORD="$(openssl rand -hex 24)"
    printf '%s' "$DB_PASSWORD" >"$PASSWORD_FILE"
    chmod 600 "$PASSWORD_FILE"
  fi
  cat >.env <<ENV
# Arena sandbox runtime configuration — generated by scripts/arena/prepare.sh.
# Disposable sandbox database; NOT a production configuration.
NODE_ENV=development
APP_TIMEZONE=Asia/Dubai
APP_DEFAULT_CURRENCY=USD

API_HOST=${ARENA_API_HOST:-0.0.0.0}
API_PORT=3101
API_CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000${SANDBOX_ID:+,https://3000-$SANDBOX_ID.e2b.app}

DATABASE_URL=postgresql://$DB_ROLE:$DB_PASSWORD@127.0.0.1:5432/$DB_NAME?schema=public

AUTH_JWT_SECRET=$(openssl rand -hex 32)
AUTH_JWT_REFRESH_SECRET=$(openssl rand -hex 32)
AUTH_JWT_EXPIRES_IN=15m
AUTH_JWT_REFRESH_EXPIRES_IN=7d

ATTACHMENT_STORAGE_DIR=$TOOLS_DIR/attachments
ATTACHMENT_URL_SECRET=$(openssl rand -hex 32)

# Sandbox only: binaries.prisma.sh is unreachable, engines are served locally.
PRISMA_ENGINES_MIRROR=http://127.0.0.1:$MIRROR_PORT

# scripts/start-api.sh preflight: the API may only open this disposable database.
PHASE11_APPROVED_DB_NAME=$DB_NAME
ENV
  chmod 600 .env
  echo "wrote .env (database $DB_NAME, role $DB_ROLE)"
else
  echo ".env already present; leaving it untouched"
fi

if [[ ! -f apps/web/.env.local ]]; then
  cat >apps/web/.env.local <<'ENV'
# Arena sandbox — same-origin browser API, server-side upstream.
NEXT_PUBLIC_API_URL=/api/v1
API_INTERNAL_URL=http://127.0.0.1:3101
# Sandbox preview diagnostics: GET /api/diag reports which credential channels arrive.
WEB_DIAGNOSTICS=1
ENV
  echo "wrote apps/web/.env.local"
else
  echo "apps/web/.env.local already present; leaving it untouched"
fi

# dotenv is not exported to child processes: read the values this script needs.
env_value() {
  sed -n "s/^$1=//p" .env | tail -1
}
export PRISMA_ENGINES_MIRROR="$(env_value PRISMA_ENGINES_MIRROR)"
export PHASE11_APPROVED_DB_NAME="$(env_value PHASE11_APPROVED_DB_NAME)"

# --------------------------------------------------------------------------
# 2. Dependencies
# --------------------------------------------------------------------------
if [[ "$SKIP_INSTALL" -eq 0 ]]; then
  step "pnpm install"
  if [[ ! -d node_modules ]]; then
    command -v pnpm >/dev/null 2>&1 || npm install --global pnpm@9.15.9
    pnpm install
  else
    echo "node_modules present; skipping"
  fi
fi

# --------------------------------------------------------------------------
# 3. Prisma engine mirror
# --------------------------------------------------------------------------
step "prisma engine mirror"
MIRROR_URL="${PRISMA_ENGINES_MIRROR:-http://127.0.0.1:$MIRROR_PORT}"
if curl -fsS -o /dev/null "$MIRROR_URL/all_commits/probe" 2>/dev/null ||
  curl -s -o /dev/null "$MIRROR_URL/" 2>/dev/null; then
  echo "mirror answering at $MIRROR_URL"
else
  echo "mirror NOT answering at $MIRROR_URL — start it with:" >&2
  echo "  node scripts/arena/engine-mirror.mjs" >&2
  exit 1
fi

# --------------------------------------------------------------------------
# 4. PostgreSQL
# --------------------------------------------------------------------------
step "postgresql"
ARENA_PG_PACKAGE="$PG_PACKAGE" node scripts/arena/db.mjs start
node scripts/arena/db.mjs provision

# --------------------------------------------------------------------------
# 5. Schema and seed
# --------------------------------------------------------------------------
step "prisma generate + migrate deploy"
pnpm db:generate
pnpm db:migrate:deploy

step "seed (required reference data)"
if [[ "$WITH_DEMO" -eq 1 ]]; then
  echo "SEED_DEMO_DATA=true — writing fabricated sample records into the sandbox database"
  SEED_DEMO_DATA=true pnpm db:seed
else
  pnpm db:seed
fi

# --------------------------------------------------------------------------
# 6. Builds
# --------------------------------------------------------------------------
if [[ "$SKIP_BUILD" -eq 0 ]]; then
  step "build api"
  pnpm build:api
  step "build web"
  pnpm build:web
else
  echo "skipping builds (--skip-build)"
fi

step "done"
cat <<'NEXT'
Next (start with the Arena process tools so they show as live previews):
  node scripts/arena/engine-mirror.mjs
  PHASE11_APPROVED_DB_NAME=duna_seed_test bash scripts/start-api.sh
  (cd apps/web && npx next start -H 0.0.0.0 -p 3000)
Then: bash scripts/arena/status.sh
NEXT
